package com.example.data.bot

object TelegramSupportBotEngine {

    fun generateReply(userMessage: String): String {
        val q = userMessage.trim().lowercase()

        return when {
            // Commands
            q == "/start" || q.contains("شروع") -> {
                """
                ✨ به پشتیبانی نکسا (Nexa Support) خوش آمدید!
                
                تیم پشتیبانی نکسا در خدمت شماست تا تجربه پیام‌رسانی سریع، امن و پایدار را برای شما فراهم کند.
                
                📌 بخش‌های راهنما:
                🔹 /help - راهنمای جامع پیام‌رسان نکسا
                🔹 /online - راهنمای چت آنلاین و سراسری
                🔹 /features - فهرست امکانات پیام‌رسان نکسا
                🔹 /room - نحوه ایجاد چت‌روم با دوستان
                
                هر سوالی در مورد پروفایل، تماس، ویس، استیکر یا چت‌ها دارید مطرح کنید.
                """.trimIndent()
            }

            q == "/help" || q.contains("راهنما") || q.contains("کمک") -> {
                """
                📚 راهنمای جامع پیام‌رسان نکسا (Nexa):
                
                ۱. چت آنلاین سراسری:
                گفتگوی «چت آنلاین سراسری 🌐» برای گفتگو با کلیه کاربران برنامه است.
                
                ۲. ایجاد چت‌روم اختصاصی:
                از آیکون 🌐 بالای صفحه یا منوی کناری، یک کد اتاق تعیین کنید و با دوستانتان به اشتراک بگذارید.
                
                ۳. پیام صوتی (ویس):
                آیکون میکروفون 🎤 را لمس کنید تا ضبط آغاز شود و مجدد برای ارسال بزنید.
                
                ۴. استیکرها و واکنش‌ها:
                آیکون استیکر 😊 را لمس کنید یا روی هر پیام برای ریپلای و واکنش ایموجی نگه دارید.
                """.trimIndent()
            }

            q == "/online" || q.contains("آنلاین") || q.contains("اینترنت") || q.contains("ارتباط") || q.contains("وصل") -> {
                """
                🌐 راهنمای قابلیت آنلاین نکسا:
                
                پیام‌رسان نکسا مجهز به سیستم همگام‌سازی ابری امن است:
                • نشانگر وضعیت اتصال در نوار بالای صفحه اصلی قابل مشاهده است.
                • تمام پیام‌ها در اتاق‌های آنلاین به سرعت بین کاربران مبادله می‌شوند.
                • امنیت داده‌ها و حریم خصوصی اولویت اصلی نکسا است.
                """.trimIndent()
            }

            q == "/room" || q.contains("کد روم") || q.contains("چت روم") || q.contains("اتاق") || q.contains("کد") -> {
                """
                🔑 نحوه چت خصوصی در نکسا با کد روم:
                
                ۱. دکمه 🌐 (اتاق‌های آنلاین) بالای صفحه اصلی را انتخاب کنید.
                ۲. یک کد دلخواه (مثلا: nexa_friends) و عنوان وارد کنید.
                ۳. دوستان شما با وارد کردن همین کد بلافاصله به اتاق شما می‌پیوندند.
                """.trimIndent()
            }

            q == "/features" || q.contains("امکانات") || q.contains("ویژگی") || q.contains("قابلیت") -> {
                """
                ⚡ امکانات شاخص پیام‌رسان نکسا (Nexa):
                
                ✅ چت آنلاین اینترنتی زنده و پایدار
                ✅ همگام‌سازی و دسترسی سریع به مخاطبین گوشی 📱
                ✅ چت خصوصی و پیوی اختصاصی
                ✅ احراز هویت امن با شماره همراه و سرورهای نکستا
                ✅ مدیریت و شخصی‌سازی پروفایل، عکس و نام کاربری 👤
                ✅ ارسال پیام متنی، ویس صوتی 🎤، استیکر و فایل
                ✅ ریپلای، سنجاق پیام و واکنش ایموجی
                ✅ تماس صوتی و تصویری با کیفیت بالا 📞
                ✅ حالت تم شب و روز (Dark / Light)
                ✅ جستجوی هوشمند و سریع در نام مخاطبین و متن پیام‌ها 🔍
                """.trimIndent()
            }

            q.contains("ویس") || q.contains("صدا") || q.contains("صوتی") || q.contains("میکروفون") -> {
                """
                🎤 راهنمای ارسال پیام صوتی:
                در پایین صفحه چت، آیکون میکروفون 🎤 را لمس کنید. زمان ضبط نمایش داده می‌شود و پس از اتمام، دکمه ارسال را بزنید.
                """.trimIndent()
            }

            q.contains("تماس") || q.contains("زنگ") || q.contains("call") -> {
                """
                📞 راهنمای تماس صوتی:
                در نوار بالای هر گفتگو، آیکون تماس را لمس کنید تا تماس با کیفیت برقرار شود.
                """.trimIndent()
            }

            q.contains("تم") || q.contains("دارک") || q.contains("شب") || q.contains("سیاه") || q.contains("روشن") -> {
                """
                🌙 تغییر حالت شب و روز:
                منوی کناری پیام‌رسان نکسا (آیکون ☰) را باز کنید و با لمس آیکون ماه/خورشید، تم دلخواه خود را فعال کنید.
                """.trimIndent()
            }

            q.contains("سلام") || q.contains("درود") || q.contains("خوبی") || q.contains("صبح") || q.contains("عصر") -> {
                """
                سلام و درود! 👋
                پشتیبانی نکسا در خدمت شماست. چطور می‌توانیم به شما کمک کنیم؟
                
                می‌توانید کلمه «راهنما» یا دستور /help را ارسال فرمایید.
                """.trimIndent()
            }

            q.contains("پروفایل") || q.contains("اسم") || q.contains("بیو") || q.contains("عکس") || q.contains("نام") -> {
                """
                👤 راهنمای پروفایل کاربری نکسا:
                از منوی کناری، روی کارت پروفایل خود یا گزینه «تنظیمات» بزنید. در آنجا می‌توانید نام نمایشی، تصویر آواتار، شماره تلفن تایید شده در نکستا و بیوگرافی خود را تنظیم کنید.
                """.trimIndent()
            }

            q.contains("گروه") || q.contains("کانال") -> {
                """
                👥 ساخت گروه جدید:
                از منوی کناری گزینه «گروه جدید» را انتخاب کنید یا از دکمه شناور ✏️ در صفحه اصلی اقدام نمایید.
                """.trimIndent()
            }

            q.contains("استیکر") || q.contains("ایموجی") || q.contains("sticker") -> {
                """
                😍 استیکرها و واکنش‌ها در نکسا:
                روی آیکون صورتک در نوار پیام بزنید تا استیکر ارسال شود. با نگه‌داشتن روی هر پیام، منوی واکنش سریع ایموجی باز می‌شود.
                """.trimIndent()
            }

            q.contains("مرسی") || q.contains("ممنون") || q.contains("تشکر") || q.contains("دستت درد نکنه") -> {
                """
                باعث افتخار ماست! 🌸
                تیم پشتیبانی نکسا همواره در کنار شماست.
                """.trimIndent()
            }

            else -> {
                """
                پیام شما دریافت شد 📨
                
                چنانچه درباره امکانات نکسا سوالی دارید، می‌توانید:
                • کلمه «راهنما» یا /help را برای مشاهده لیست بخش‌ها بنویسید.
                • عبارت «چت آنلاین» برای آشنایی با اتاق‌های آنلاین.
                • عبارت «پروفایل» برای راهنمای تنظیم مشخصات کاربری.
                
                پشتیبانی نکسا همواره در خدمت شماست.
                """.trimIndent()
            }
        }
    }
}
