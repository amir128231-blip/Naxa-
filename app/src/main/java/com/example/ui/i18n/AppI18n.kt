/**
 * Returns strings bundle based on language
 */
fun getStringsForLanguage(language: AppLanguage): AppStrings {
    return when (language) {
        AppLanguage.PERSIAN -> PersianStrings
        AppLanguage.ENGLISH -> EnglishStrings
        AppLanguage.ARABIC -> ArabicStrings
        AppLanguage.RUSSIAN -> RussianStrings
        AppLanguage.TURKISH -> TurkishStrings
        AppLanguage.SPANISH -> SpanishStrings
        AppLanguage.GERMAN -> GermanStrings
        AppLanguage.FRENCH -> FrenchStrings
        AppLanguage.CHINESE -> ChineseStrings
        AppLanguage.HINDI,
        AppLanguage.ITALIAN,
        AppLanguage.JAPANESE,
        AppLanguage.KOREAN,
        AppLanguage.PORTUGUESE,
        AppLanguage.INDONESIAN,
        AppLanguage.AZERBAIJANI -> EnglishStrings.copy(
            appTitle = "Nexa (${language.nativeName})",
            selectLanguage = "${language.nativeName} (${language.displayName})"
        )
        AppLanguage.KURDISH,
        AppLanguage.URDU -> ArabicStrings.copy(
            appTitle = "نکسا (${language.nativeName})",
            selectLanguage = "${language.nativeName} (${language.displayName})"
        )
    }
}

