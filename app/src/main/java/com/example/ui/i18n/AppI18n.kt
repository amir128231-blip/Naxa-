/**
 * Supported Languages in Nexa (Telegram-style global messaging app)
 */
enum class AppLanguage(
    val code: String,
    val displayName: String,
    val nativeName: String,
    val flagEmoji: String,
    val layoutDirection: LayoutDirection
) {
    PERSIAN("fa", "Persian", "فارسی", "🇮🇷", LayoutDirection.Rtl),
    ENGLISH("en", "English", "English", "🇺🇸", LayoutDirection.Ltr),
    ARABIC("ar", "Arabic", "العربية", "🇸🇦", LayoutDirection.Rtl),
    RUSSIAN("ru", "Russian", "Русский", "🇷🇺", LayoutDirection.Ltr),
    TURKISH("tr", "Turkish", "Türkçe", "🇹🇷", LayoutDirection.Ltr),
    SPANISH("es", "Spanish", "Español", "🇪🇸", LayoutDirection.Ltr),
    GERMAN("de", "German", "Deutsch", "🇩🇪", LayoutDirection.Ltr),
    FRENCH("fr", "French", "Français", "🇫🇷", LayoutDirection.Ltr),
    CHINESE("zh", "Chinese", "中文 (简体)", "🇨🇳", LayoutDirection.Ltr),
    HINDI("hi", "Hindi", "हिन्दी", "🇮🇳", LayoutDirection.Ltr),
    ITALIAN("it", "Italian", "Italiano", "🇮🇹", LayoutDirection.Ltr),
    JAPANESE("ja", "Japanese", "日本語", "🇯🇵", LayoutDirection.Ltr),
    KOREAN("ko", "Korean", "한국어", "🇰🇷", LayoutDirection.Ltr),
    PORTUGUESE("pt", "Portuguese", "Português", "🇧🇷", LayoutDirection.Ltr),
    INDONESIAN("id", "Indonesian", "Bahasa Indonesia", "🇮🇩", LayoutDirection.Ltr),
    KURDISH("ku", "Kurdish", "کوردی", "☀️", LayoutDirection.Rtl),
    AZERBAIJANI("az", "Azerbaijani", "Azərbaycan", "🇦🇿", LayoutDirection.Ltr),
    URDU("ur", "Urdu", "اردو", "🇵🇰", LayoutDirection.Rtl);

    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.find { it.code.equals(code, ignoreCase = true) } ?: fromSystemLocale()
        }

        fun fromSystemLocale(): AppLanguage {
            val locale = java.util.Locale.getDefault()
            val lang = locale.language.lowercase()
            return when {
                lang.startsWith("fa") || lang.startsWith("prs") || lang.startsWith("per") -> PERSIAN
                lang.startsWith("en") -> ENGLISH
                lang.startsWith("ar") -> ARABIC
                lang.startsWith("ru") -> RUSSIAN
                lang.startsWith("tr") -> TURKISH
                lang.startsWith("es") -> SPANISH
                lang.startsWith("de") -> GERMAN
                lang.startsWith("fr") -> FRENCH
                lang.startsWith("zh") -> CHINESE
                lang.startsWith("hi") -> HINDI
                lang.startsWith("it") -> ITALIAN
                lang.startsWith("ja") -> JAPANESE
                lang.startsWith("ko") -> KOREAN
                lang.startsWith("pt") -> PORTUGUESE
                lang.startsWith("id") || lang.startsWith("in") -> INDONESIAN
                lang.startsWith("ku") -> KURDISH
                lang.startsWith("az") -> AZERBAIJANI
                lang.startsWith("ur") -> URDU
                else -> entries.find { it.code.equals(lang, ignoreCase = true) } ?: PERSIAN
            }
        }
    }
}

